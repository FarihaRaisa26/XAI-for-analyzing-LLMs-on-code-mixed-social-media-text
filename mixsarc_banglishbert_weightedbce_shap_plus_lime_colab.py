"""## Cell 28 — Token-aligned SHAP–LIME comparison

Compare only identical **sentence ID + output label + token position**, and only when the text segmentation matches. Outputs: Top-5 token Jaccard, sign agreement on nonzero overlapping top tokens, and Spearman correlation where defined. SHAP and LIME values have different semantics; do **not** compare raw numeric magnitudes as equivalent effect sizes.
"""

if not LIME_SHAP_PATH.exists():
    print('Skipping SHAP comparison: file not found:', LIME_SHAP_PATH)
else:
    shap_wide = pd.read_csv(LIME_SHAP_PATH, keep_default_na=False)
    expected = {'sentence_id','token_position','token_normalized'} | set(SHAP_COLUMNS)
    assert expected.issubset(shap_wide.columns)
    shap_wide['sentence_id'] = shap_wide['sentence_id'].astype(int)
    shap_wide['token_position'] = shap_wide['token_position'].astype(int)
    comparisons, matched_rows = [], []
    for _,row in selected.iterrows():
        sid, label = int(row.sentence_id), str(row.target_label)
        ldf = (lime_local[(lime_local.sentence_id==sid) & (lime_local.target_label==label)]
               .sort_values('token_position').reset_index(drop=True))
        sdf = (shap_wide[shap_wide.sentence_id==sid]
               .sort_values('token_position').reset_index(drop=True))
        alignment_ok = (len(ldf)==len(sdf) and
            ldf['token_position'].astype(int).tolist()==sdf['token_position'].astype(int).tolist() and
            ldf['token_normalized'].astype(str).str.casefold().tolist()==
            sdf['token_normalized'].astype(str).str.casefold().tolist())
        base = {'sentence_id':sid, 'target_label':label, 'status':str(row.status),
                'tokens_aligned':bool(alignment_ok),'n_lime_tokens':len(ldf),'n_shap_tokens':len(sdf),
                'local_surrogate_r2':float(ldf.local_surrogate_r2.iloc[0])}
        if not alignment_ok:
            comparisons.append({**base, 'topk_jaccard':np.nan,
                                'topk_sign_agreement':np.nan,'spearman_rho':np.nan})
            continue
        a = ldf['lime_weight'].astype(float).to_numpy()
        b = sdf[LABEL_TO_SHAP_COLUMN[label]].astype(float).to_numpy()
        k=min(LIME_TOP_K,len(a))
        top_lime=set(np.argsort(-np.abs(a))[:k].tolist())
        top_shap=set(np.argsort(-np.abs(b))[:k].tolist())
        overlap=top_lime & top_shap
        comparable = [i for i in overlap if abs(a[i])>1e-8 and abs(b[i])>1e-8]
        sign_agreement = (float(np.mean([np.sign(a[i])==np.sign(b[i]) for i in comparable]))
                          if comparable else np.nan)
        rho = (float(spearmanr(a,b).statistic)
               if len(a)>=3 and np.std(a)>1e-12 and np.std(b)>1e-12 else np.nan)
        comparisons.append({**base, 'topk_jaccard':len(overlap)/len(top_lime|top_shap),
                            'topk_sign_agreement':sign_agreement,'spearman_rho':rho})
        aligned = ldf[['sentence_id','target_label','status','token_position','token','lime_weight']].copy()
        aligned['shap_value'] = b
        matched_rows.append(aligned)
    comparison_df = pd.DataFrame(comparisons)
    comparison_df.to_csv(LIME_OUTPUT_DIR/'shap_lime_case_agreement.csv',index=False,float_format='%.12g')
    if matched_rows:
        pd.concat(matched_rows,ignore_index=True).to_csv(
            LIME_OUTPUT_DIR/'shap_lime_matched_token_values.csv',index=False,float_format='%.12g')
    display(comparison_df)
    print('Aligned cases:',int(comparison_df.tokens_aligned.sum()),'/',len(comparison_df))
    print('Do not report agreement scores for unaligned cases.')

