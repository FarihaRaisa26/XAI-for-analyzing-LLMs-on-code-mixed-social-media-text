"""### Cell 8A — Mandatory saved-model verification and backup

The original training code calls `trainer.save_model(MODEL_DIR)`. Here we verify that it actually produced model **weights** (not just `config.json`). If weights are missing, `save_pretrained` is attempted immediately while the trained model remains in memory. The cell stops if trained weights still cannot be found.

For additional protection, save the model directory in a separate backup ZIP after all explanations finish (last cell). The prior SHAP results ZIP is unchanged.
"""

# Safeguard against a config/tokenizer-only best_model folder.
# This cell runs just after training, while the original trained model is still in memory.
WEIGHT_CANDIDATES = (
    'model.safetensors', 'pytorch_model.bin',
    'model.safetensors.index.json', 'pytorch_model.bin.index.json'
)

def model_weight_files(folder):
    """Report loadable Hugging Face save_pretrained weight files or weight indices."""
    return [folder / name for name in WEIGHT_CANDIDATES if (folder / name).is_file()]

weight_files = model_weight_files(MODEL_DIR)
if not weight_files:
    print('Trainer save had no visible weight file. Saving model directly again...')
    trainer.model.save_pretrained(str(MODEL_DIR), safe_serialization=True)
    tokenizer.save_pretrained(str(MODEL_DIR))
    weight_files = model_weight_files(MODEL_DIR)
if not weight_files:
    raise RuntimeError('MODEL WEIGHTS WERE NOT SAVED. Stop now; do not proceed to SHAP or LIME.')

file_manifest = {p.name: int(p.stat().st_size) for p in MODEL_DIR.iterdir() if p.is_file()}
if all(p.stat().st_size < 1024 * 1024 for p in weight_files):
    # A sharded index can be small; check for shard files, too.
    shards = list(MODEL_DIR.glob('model-*.safetensors')) + list(MODEL_DIR.glob('pytorch_model-*.bin'))
