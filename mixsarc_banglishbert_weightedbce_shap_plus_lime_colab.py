"""## Cell 27 — Run and save local LIME explanations

Use the same four-output `trainer.model` as SHAP, but explain one label at a time via binary probability wrappers. A separate `parts` file is saved for each `(sentence_id, target_label)` so interrupted Colab runs can resume. Save token-level signed weights and local surrogate `R²`. A low R² suggests the local linear approximation may be unreliable.
"""

all_part_paths = []
for case_number, row in tqdm(list(selected.iterrows()), desc='LIME cases'):
    sid = int(row['sentence_id'])
    label = str(row['target_label'])
    label_index = LABELS.index(label)
    part = LIME_PARTS_DIR / f'sentence_{sid:06d}_{label}.csv'
    all_part_paths.append(part)
    if part.exists():
        continue   # resume previous saved explanation for identical configuration

    sentence = str(row['sentence'])
    visible_tokens = lime_word_punct_tokens(sentence)
    case_seed = (SEED + 100_003*label_index + sid) % (2**32-1)
    explainer = LimeTextExplainer(
        class_names=[f'not_{label}', label],
        split_expression=lime_word_punct_tokens,
        bow=False,                  # positions matter for repeated tokens
        mask_string=tokenizer.mask_token or '[MASK]',
        random_state=case_seed,
        feature_selection='auto'
    )
    exp = explainer.explain_instance(
        sentence,
        classifier_fn=lime_label_classifier(label_index),
        labels=(1,),
        num_features=len(visible_tokens),
        num_samples=LIME_NUM_SAMPLES
    )
    # First row of the LIME perturbed batch should reproduce the original sentence.
    assert abs(float(exp.predict_proba[1]) - float(row['predicted_probability'])) < 1e-3
    weights_by_position = {int(idx):float(value) for idx,value in exp.local_exp[1]}
    case_rows = []
    for token_index, token in enumerate(visible_tokens):
        w = weights_by_position.get(token_index, 0.0)
        case_rows.append({
            'sentence_id':sid,'sentence':sentence,'target_label':label,
            'status':str(row['status']),'gold_label':int(row['gold_label']),
            'predicted_label':int(row['predicted_label']),
            'predicted_probability':float(row['predicted_probability']),
            'threshold':float(row['threshold']),
            'token_position':token_index,'token':token,
            'token_normalized':token.casefold(),
            'lime_weight':w, 'abs_lime_weight':abs(w),
            'local_surrogate_r2':float(exp.score),
            'lime_num_samples':LIME_NUM_SAMPLES,'lime_seed':int(case_seed)
        })
    temp = part.with_suffix('.tmp')
    pd.DataFrame(case_rows).to_csv(temp,index=False,float_format='%.12g')
    os.replace(temp, part)

